// Share the exact 10x10 rules and search with a background analysis worker.
const fs = require('node:fs');
const html = fs.readFileSync('index.html', 'utf8');
const constants = html.slice(html.indexOf('const Ht ='), html.indexOf('// French is a separate'));
const engine = html.slice(html.indexOf('class rr {'), html.indexOf('const Jh ='));
const handler = `
self.onmessage = ({ data }) => {
  try {
    FRENCH_MODE = !!data.french;
    const pos = new rr(), history = [pos.key()];
    const find = code => pos.legalMoves().find(m => m.from === code.from && m.to === code.to && (m.promo || 0) === (code.promo || 0));
    for (const code of data.moves.slice(0, -1)) {
      const move = find(code); if (!move) throw Error('Invalid history');
      pos.make(move); history.push(pos.key());
    }
    const played = find(data.moves[data.moves.length - 1]);
    if (!played) throw Error('Invalid move');
    const candidates = pos.legalMoves(); $f(candidates);
    let complete, depth = 0;
    const deadline = Date.now() + 1000;
    for (let d = 1; d <= 2; d++) {
      const state = { nodes: 0, deadline, check: true, aborted: false, repetitions: new Map() };
      for (const key of history) state.repetitions.set(key, (state.repetitions.get(key) || 0) + 1);
      const scores = [];
      for (const move of candidates) {
        pos.make(move);
        const score = -gr(pos, d - 1, -1e9, 1e9, 1, state);
        pos.unmake();
        if (state.aborted || Date.now() > deadline) { state.aborted = true; break; }
        scores.push({ move, score });
      }
      if (state.aborted) break;
      complete = scores; depth = d;
    }
    if (!complete) throw Error('Analysis timed out');
    complete.sort((a, b) => b.score - a.score);
    const chosen = complete.find(({ move }) => move.from === played.from && move.to === played.to && move.promo === played.promo);
    const bestMove = chosen.score === complete[0].score;
    // Conservative heuristic, not chess.com's proprietary brilliant algorithm.
    pos.make(played);
    const sacrifice = pos.legalMoves().some(m => m.to === played.to && Math.abs(m.captured) === Math.abs(played.piece) && Vf[Math.abs(played.piece)] > Vf[Math.abs(m.piece)] + (Vf[Math.abs(played.captured)] || 0));
    self.postMessage({ best: complete[0].score, played: chosen.score, second: complete[1]?.score ?? complete[0].score, bestMove, sacrifice, depth, alternative: { from: complete[0].move.from, to: complete[0].move.to, promo: complete[0].move.promo }, whiteScore: chosen.score * Math.sign(played.piece) });
  } catch { self.postMessage({ error: true }); }
};
`;
const source = '// Generated by scripts/sync-coach.cjs; do not edit.\nlet FRENCH_MODE = false;\n' + constants + engine + handler;
const rules = '// Generated by scripts/sync-coach.cjs; do not edit.\nmodule.exports = function(FRENCH_MODE = false) {\n' + constants + engine + '\nreturn { rr, Ge, Vf };\n};\n';
if (process.argv.includes('--check')) {
  if (fs.readFileSync('lib/coach-rules.cjs', 'utf8') !== rules) throw Error('Run node scripts/sync-coach.cjs');
  if (fs.readFileSync('assets/coach-worker.js', 'utf8') !== source) throw Error('Run node scripts/sync-coach.cjs');
} else { fs.writeFileSync('assets/coach-worker.js', source); fs.writeFileSync('lib/coach-rules.cjs', rules); }
