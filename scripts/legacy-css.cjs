// Keep the bundled utilities usable on whiteboard browsers without CSS cascade layers.
const fs = require('node:fs');
function legacyCSS(html) {
  const css = [...html.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)].map(m => m[1]).find(s => s.includes('@layer properties'));
  if (!css) throw Error('Bundled utility stylesheet not found');
  // Strip only layer wrappers, retaining nested @media/@supports blocks and rule order.
  let result = '', stack = [], quote = '', escaped = false;
  for (let i = 0; i < css.length; i++) {
    const c = css[i];
    if (quote) {
      result += c;
      if (escaped) escaped = false;
      else if (c === '\\') escaped = true;
      else if (c === quote) quote = '';
      continue;
    }
    if (c === '"' || c === "'") { quote = c; result += c; continue; }
    if (css.startsWith('@layer', i)) {
      const end = css.slice(i).search(/[;{]/);
      if (end < 0) throw Error('Unterminated layer');
      if (css[i + end] === '{') stack.push(true);
      i += end; continue;
    }
    if (c === '{') stack.push(false);
    if (c === '}' && stack.pop()) continue;
    result += c;
  }
  // Older Chromium does not understand OKLCH; convert literal palette colors to sRGB.
  result = result.replace(/oklch\(([\d.]+)(%?)\s+([\d.]+)\s+([\d.]+)\)/g, (_, l, percent, c, h) => {
    l = Number(l) / (percent ? 100 : 1); c = Number(c); h = Number(h) * Math.PI / 180;
    const a = c * Math.cos(h), b = c * Math.sin(h);
    const L = (l + .3963377774*a + .2158037573*b)**3;
    const M = (l - .1055613458*a - .0638541728*b)**3;
    const S = (l - .0894841775*a - 1.291485548*b)**3;
    const rgb = [4.0767416621*L - 3.3077115913*M + .2309699292*S, -1.2684380046*L + 2.6097574011*M - .3413193965*S, -.0041960863*L - .7034186147*M + 1.707614701*S];
    return '#' + rgb.map(v => Math.round(Math.max(0, Math.min(1, v <= .0031308 ? 12.92*v : 1.055*v**(1/2.4)-.055))*255).toString(16).padStart(2, '0')).join('');
  });
  // @property initial values are not available on older engines.
  result += '\n*,::before,::after { --tw-border-style: solid; --tw-leading: normal; --tw-font-weight: 400; }\n';
  return '/* Generated by scripts/legacy-css.cjs; do not edit directly. */\n' + result;
}
module.exports = legacyCSS;
if (require.main === module) fs.writeFileSync('assets/legacy-layout.css', legacyCSS(fs.readFileSync('index.html', 'utf8')));
