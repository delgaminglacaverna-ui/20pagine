// index.html is the source of truth for the existing chess rules.
const fs = require('node:fs');
const html = fs.readFileSync('index.html', 'utf8');
const constants = html.slice(html.indexOf('const Ht ='), html.indexOf('// French is a separate'));
const engine = html.slice(html.indexOf('class rr {'), html.indexOf('function ir('));
if (!constants.startsWith('const Ht =') || !engine.startsWith('class rr {')) throw Error('Chess engine boundaries changed');
const source = '// Generated by scripts/sync-engine.cjs; do not edit.\nconst FRENCH_MODE = false;\n' + constants + engine + '\nmodule.exports = rr;\n';
if (process.argv.includes('--check')) {
  if (fs.readFileSync('lib/chess.cjs', 'utf8') !== source) throw Error('Run node scripts/sync-engine.cjs');
} else fs.writeFileSync('lib/chess.cjs', source);
